// Writes public/assets/qr.js: one QR code (error correction M) per language home page, as rows of
// "0"/"1" modules, for the share poster. The site loads nothing from third parties, so the codes are
// made here once with macOS CoreImage and committed. Re-run only if the URLs change:
//   swift tools/make-qr.swift > public/assets/qr.js
import CoreImage
import Foundation

let site = "https://nu-time.org"
let langs = ["en", "zh", "ja", "hi", "ur", "es", "pt", "fr", "de", "it", "ru"]
let ctx = CIContext(options: nil)

func modules(_ text: String) -> [String] {
    let f = CIFilter(name: "CIQRCodeGenerator")!
    f.setValue(text.data(using: .utf8), forKey: "inputMessage")
    f.setValue("M", forKey: "inputCorrectionLevel")
    let img = f.outputImage!
    let w = Int(img.extent.width), h = Int(img.extent.height)
    var px = [UInt8](repeating: 0, count: w * h * 4)
    ctx.render(img, toBitmap: &px, rowBytes: w * 4, bounds: img.extent, format: .RGBA8, colorSpace: CGColorSpaceCreateDeviceRGB())
    var rows: [String] = []
    for y in 0..<h {   // render(toBitmap:) writes the top row first
        var r = ""
        for x in 0..<w { r += px[(y * w + x) * 4] < 128 ? "1" : "0" }
        rows.append(r)
    }
    // CoreImage adds a quiet zone; trim all-white border rows/columns so the poster controls the margin
    while let f = rows.first, !f.contains("1") { rows.removeFirst() }
    while let l = rows.last, !l.contains("1") { rows.removeLast() }
    let left = rows.map { $0.distance(from: $0.startIndex, to: $0.firstIndex(of: "1")!) }.min()!
    let right = rows.map { $0.count - 1 - $0.distance(from: $0.startIndex, to: $0.lastIndex(of: "1")!) }.min()!
    return rows.map { String($0.dropFirst(left).dropLast(right)) }
}

var out = "// Generated by tools/make-qr.swift — do not edit. QR codes (level M) for each language's home page.\nwindow.NT_QR = {\n"
for l in langs {
    let url = l == "en" ? site + "/" : "\(site)/\(l)/"
    let rows = modules(url).map { "\"\($0)\"" }.joined(separator: ",")
    out += "  \"\(l)\": { url: \"\(url)\", rows: [\(rows)] },\n"
}
out += "};\n"
print(out, terminator: "")
